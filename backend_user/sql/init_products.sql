-- Supabase SQL Editor에서 실행하는 상품 테이블 초기화 스크립트입니다.
-- 기존 테이블을 삭제하지 않으므로, 여러 번 실행해도 안전합니다.

-- 상품 정보를 저장할 테이블을 생성합니다.
CREATE TABLE IF NOT EXISTS public.products (
    -- 애플리케이션이 생성하는 문자열 형태의 상품 ID입니다.
    id TEXT PRIMARY KEY,
    -- 빈 문자열은 허용하지 않는 상품 이름입니다.
    name TEXT NOT NULL CHECK (char_length(trim(name)) > 0),
    -- 가격은 원 단위 정수이며 최소 1원입니다.
    price INTEGER NOT NULL CHECK (price >= 1),
    -- 시간대를 포함한 생성 시각입니다.
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 생성 시각 기준으로 목록을 조회할 때 사용할 인덱스입니다.
CREATE INDEX IF NOT EXISTS idx_products_created_at
    ON public.products (created_at DESC);

